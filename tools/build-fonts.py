"""
Subset the poster fonts to Latin text, write WOFF2 files for the web page, and
write js/font-metrics.js (advance widths) so the layout engine can measure text
in Node and in the browser without loading a font.

    pip install fonttools brotli
    python tools/build-fonts.py

Fira Sans (SIL OFL) stands in for BKK's Frutiger. Share Tech Mono (SIL OFL) draws
the amber LED destination signs.
"""
import json
import os

from fontTools import subset
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "fonts-src")
OUT_FONTS = os.path.join(HERE, "..", "fonts")
OUT_JS = os.path.join(HERE, "..", "js", "font-metrics.js")

# key used by the layout code -> (file, CSS weight, CSS style)
FONTS = {
    "F-Reg": ("FiraSans-Regular.ttf", 400, "normal"),
    "F-Med": ("FiraSans-Medium.ttf", 500, "normal"),
    "F-Semi": ("FiraSans-SemiBold.ttf", 600, "normal"),
    "F-Bold": ("FiraSans-Bold.ttf", 700, "normal"),
    "F-Ital": ("FiraSans-Italic.ttf", 400, "italic"),
    "LED": ("ShareTechMono-Regular.ttf", 400, "normal"),
}

# Basic Latin, Latin-1, Latin Extended-A, and the punctuation GTFS names use.
UNICODES = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x180))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2032, 0x00B7]
)


def main():
    os.makedirs(OUT_FONTS, exist_ok=True)
    metrics = {}
    for key, (fname, weight, style) in FONTS.items():
        src = os.path.join(SRC, fname)
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = []          # no kerning/ligatures: widths must match the metrics
        opts.name_IDs = [1, 2, 3, 4, 6]
        opts.notdef_outline = True
        opts.hinting = False
        font = TTFont(src)
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=UNICODES)
        sub.subset(font)
        out = os.path.join(OUT_FONTS, os.path.splitext(fname)[0] + ".woff2")
        font.flavor = "woff2"
        font.save(out)

        ref = TTFont(src)
        upm = ref["head"].unitsPerEm
        cmap = ref.getBestCmap()
        hmtx = ref["hmtx"]
        adv = {}
        for cp in UNICODES:
            g = cmap.get(cp)
            if g:
                adv[cp] = hmtx[g][0]
        space = adv.get(0x20, upm // 4)
        metrics[key] = {
            "file": os.path.splitext(fname)[0] + ".woff2",
            "weight": weight,
            "style": style,
            "upm": upm,
            "def": space,
            "adv": adv,
        }
        print(f"{key:7s} {os.path.getsize(out) / 1024:6.1f} KB  {out}")

    with open(OUT_JS, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build-fonts.py. Do not edit.\n")
        fh.write("(function (root) {\n  var M = ")
        fh.write(json.dumps(metrics, separators=(",", ":")))
        fh.write(";\n  if (typeof module !== 'undefined' && module.exports) module.exports = M;\n")
        fh.write("  else root.BKK_FONT_METRICS = M;\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n")
    print("wrote", OUT_JS, os.path.getsize(OUT_JS) // 1024, "KB")


if __name__ == "__main__":
    main()
